const assert = require('node:assert/strict');
const fs = require('node:fs');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');

(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROMIUM_PATH });
  try {
    const page = await browser.newPage({ viewport: { width: 1280, height: 768 } });
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    const base = process.argv[2];
    const endpoint = `${base}/analyses/lichess/q7ZvsdUF/discussions`;
    await page.goto(`${base}/analyses/lichess/q7ZvsdUF?trainer=1`);
    const input = page.getByRole('textbox', { name: 'Discuss this Position' });
    const send = page.getByRole('button', { name: 'Send to Trainer', exact: true });
    await page.getByRole('region', { name: 'Trainer response', exact: true }).waitFor();
    assert.equal(await page.locator('.trainer-settings, #trainer-consent').count(), 0);
    let sends = 0;
    page.on('request', r => { if (r.url() === endpoint && r.method() === 'POST') sends++; });
    await input.fill('Question');
    await input.press('Shift+Enter');
    await input.press('a');
    assert.equal(await input.inputValue(), 'Question\na');
    await input.dispatchEvent('compositionstart');
    await input.dispatchEvent('keydown', { key: 'Enter', code: 'Enter' });
    assert.equal(sends, 0);
    await input.dispatchEvent('compositionend');
    await input.dispatchEvent('keydown', { key: 'Enter', code: 'Enter', isComposing: true });
    assert.equal(sends, 0);
    await input.dispatchEvent('keydown', { key: 'Enter', code: 'Enter', keyCode: 229 });
    assert.equal(sends, 0);
    let releaseAcceptance;
    const acceptanceGate = new Promise(resolve => { releaseAcceptance = resolve; });
    let requestArrived;
    const arrived = new Promise(resolve => { requestArrived = resolve; });
    await page.route(endpoint, async route => {
      const response = await route.fetch();
      requestArrived();
      await acceptanceGate;
      await route.fulfill({ response });
    }, { times: 1 });
    const accepted = page.waitForResponse(r => r.url() === endpoint && r.request().method() === 'POST');
    await input.press('Enter');
    await arrived;
    await input.fill('Draft typed while send is pending');
    await input.press('Enter');
    await send.evaluate(button => button.click());
    assert.equal(sends, 1);
    releaseAcceptance();
    assert.equal((await accepted).status(), 202);
    await page.getByText('First live paragraph.', { exact: false }).waitFor();
    assert.equal(await input.inputValue(), 'Draft typed while send is pending');
    await input.fill('My next draft');
    await input.press('Shift+Enter');
    await input.press('b');
    const draft = 'My next draft\nb';
    assert.equal(await send.isDisabled(), true);
    await input.press('Enter');
    await send.evaluate(button => button.click());
    assert.equal(sends, 1);
    const duplicate = await page.request.post(endpoint, { form: { base_ply: '0', message: 'Concurrent', stream: 'true' } });
    assert.equal(duplicate.status(), 409);
    fs.writeFileSync(`${process.argv[3]}/1`, 'release');
    await page.getByText('Live paragraph 1.', { exact: false }).waitFor();
    assert.equal(await input.inputValue(), draft);
    assert.equal(await input.evaluate(el => el === document.activeElement), true);
    if (process.argv[4] === 'interrupt') {
      await page.getByRole('button', { name: 'Interrupt response', exact: true }).click();
    } else {
      fs.writeFileSync(`${process.argv[3]}/2`, 'release');
    }
    await send.waitFor({ state: 'visible' });
    await page.waitForFunction(button => !button.disabled, await send.elementHandle());
    assert.equal(await input.inputValue(), draft);
    if (process.argv[4] === 'complete') assert.equal(await input.evaluate(el => el === document.activeElement), true);
    assert.equal(sends, 1);
    const saved = await (await page.request.get(`${endpoint}/0`)).json();
    assert.equal(saved.attempts.length, 2);
    assert.equal(saved.attempts[1].status, process.argv[4] === 'interrupt' ? 'interrupted' : 'completed');
    const explicit = page.waitForResponse(r => r.url() === endpoint && r.request().method() === 'POST');
    if (process.argv[4] === 'complete') await input.press('Enter');
    else await send.click();
    assert.equal((await explicit).status(), 202);
    assert.equal(sends, 2);
    fs.writeFileSync(`${process.argv[3]}/2`, 'release');
    await page.waitForFunction(button => !button.disabled, await send.elementHandle());
    assert.equal(await input.inputValue(), '');
    const final = await (await page.request.get(`${endpoint}/0`)).json();
    assert.equal(final.messages.filter(message => message.author === 'player').at(-1).body, draft);
    assert.deepEqual(errors, []);
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
